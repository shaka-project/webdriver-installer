const {WebDriverInstallerBase} = require('./base.js');
const {InstallerUtils} = require('./utils.js');

const fsPromises = require('fs').promises;
const os = require('os');
const path = require('path');

// When Firefox is a snap package, the real geckodriver binary is installed
// under this name, and "geckodriver" is a wrapper script that runs it.
const WRAPPED_DRIVER_NAME = 'geckodriver-bin';

// Shell scripts are small.  This is enough to read any wrapper script in full,
// without reading an entire binary into memory.
const SCRIPT_READ_LIMIT = 64 * 1024;

// The start of every wrapper script we generate.
const WRAPPER_HEADER = '#!/bin/sh\n# Generated by webdriver-installer.\n';

/**
 * Search PATH for an executable named "firefox", the same way geckodriver
 * does when no binary is specified: the first match that is an executable
 * file wins.
 *
 * @return {!Promise<?string>}
 */
async function findFirefoxOnPath() {
  for (const dir of (process.env.PATH || '').split(path.delimiter)) {
    if (!dir) {
      continue;
    }

    const candidate = path.join(dir, 'firefox');
    try {
      const stat = await fsPromises.stat(candidate);
      if (stat.isFile() && (stat.mode & 0o111)) {
        return candidate;
      }
    } catch (error) {
      // Not found here.  Keep looking.
    }
  }
  return null;
}

/**
 * Generate a geckodriver wrapper script for a snap-packaged Firefox.
 *
 * A snap has a private /tmp, but by default geckodriver creates temporary
 * Firefox profiles in the host's $TMPDIR (default /tmp), where the snap can't
 * see them.  So point TMPDIR at a directory that the snap can access.  An
 * explicit --profile-root passed to geckodriver still takes precedence.
 *
 * @param {string} snapName
 * @return {string}
 */
function getSnapWrapperScript(snapName) {
  return `${WRAPPER_HEADER}#
# The default Firefox on this system is the "${snapName}" snap, which has a
# private /tmp.  geckodriver creates temporary Firefox profiles in $TMPDIR
# (default /tmp), which the snap can't see.  So point TMPDIR at a directory
# that the snap can access.  An explicit --profile-root still takes precedence.
# See https://bugzilla.mozilla.org/show_bug.cgi?id=1819377
TMPDIR="\${HOME:?}/snap/${snapName}/common/geckodriver-tmp"
export TMPDIR
mkdir -p "$TMPDIR" || exit 1
exec "$(dirname "$(readlink -f "$0")")/${WRAPPED_DRIVER_NAME}" "$@"
`;
}

/**
 * An installer for chromedriver for desktop Firefox.
 */
class FirefoxWebDriverInstaller extends WebDriverInstallerBase {
  /** @return {string} */
  getBrowserName() {
    return 'Firefox';
  }

  /** @return {string} */
  getDriverName() {
    return 'geckodriver';
  }

  /** @return {!Promise<?string>} */
  async getInstalledBrowserVersion() {
    if (os.platform() == 'linux') {
      const output = await InstallerUtils.getCommandOutputOrNullIfMissing(
          ['firefox', '-v']);
      // Output is a string like "Mozilla Firefox 96.0"
      return output ? output.trim().split(' ')[2] : null;
    } else if (os.platform() == 'darwin') {
      // The typical "InstallerUtils.getMacAppVersion" may hang for Firefox, so
      // we use this alternate method instead.
      // See https://github.com/shaka-project/webdriver-installer/issues/47
      return this.getMacAppVersion();
    } else if (os.platform() == 'win32') {
      return await InstallerUtils.getWindowsExeVersion('firefox.exe');
    } else {
      throw new Error(`Unrecognized platform: ${os.platform()}`);
    }
  }

  /**
   * Parse the macOS Firefox ini file to get the version number.
   * @return {?string}
   */
  async getMacAppVersion() {
    const path = '/Applications/Firefox.app/Contents/Resources/application.ini';
    let data = null;
    try {
      data = await fsPromises.readFile(path, { encoding: 'utf8' });
    } catch (error) {
      // No such file, no Firefox installed.
      return null;
    }

    const match = /^Version=(.*)$/m.exec(data);
    if (!match) {
      // This shouldn't happen.  Did the file change format?
      console.error('Unable to parse Firefox version!');
      return null;
    }
    return match[1];
  }

  /**
   * On Linux, determine if the Firefox that geckodriver would launch by
   * default is a snap package.
   *
   * @return {!Promise<?string>} The snap name (e.g. "firefox"), or null.
   */
  async getSnapName() {
    if (os.platform() != 'linux') {
      return null;
    }

    const firefoxPath = await findFirefoxOnPath();
    if (!firefoxPath) {
      return null;
    }

    // Snap launchers are installed as /snap/bin/<snap> or /snap/bin/<snap>.<app>
    // when you install a snap directly.
    if (path.dirname(firefoxPath) == '/snap/bin') {
      return path.basename(firefoxPath).split('.')[0];
    }

    // Ubuntu's transitional "firefox" deb package installs /usr/bin/firefox as
    // a shell script that ends with: exec /snap/bin/firefox "$@"
    const head = await InstallerUtils.readFileHead(
        firefoxPath, SCRIPT_READ_LIMIT);
    if (!head || !head.startsWith('#!')) {
      return null;
    }
    // Snap names are lowercase letters, digits, and hyphens, plus an optional
    // "_instance" suffix.  App names would follow a ".", which is excluded.
    const match = /\/snap\/bin\/([a-z0-9_-]+)/.exec(head);
    return match ? match[1] : null;
  }

  /**
   * @param {string} outputDirectory
   * @return {!Promise<?string>}
   */
  async getInstalledDriverVersion(outputDirectory) {
    // NOTE: Using path.join here would also normalize the path, which would
    // turn something like "./geckodriver" into "geckodriver", which would
    // fail to execute.
    const outputPath = outputDirectory + path.sep + this.getDriverName();

    if (os.platform() == 'linux') {
      // If the installed driver doesn't match the current system (a snap
      // wrapper where none is needed, a missing or outdated wrapper, or a
      // wrapper whose binary is missing), report no installed version, so that
      // it gets reinstalled.
      const snapName = await this.getSnapName();
      const head = await InstallerUtils.readFileHead(
          outputPath, SCRIPT_READ_LIMIT);
      if (head != null) {
        if (snapName) {
          const wrappedPath = path.join(outputDirectory, WRAPPED_DRIVER_NAME);
          if (head != getSnapWrapperScript(snapName) ||
              !(await InstallerUtils.fileExists(wrappedPath))) {
            return null;
          }
        } else if (head.startsWith(WRAPPER_HEADER)) {
          return null;
        }
      }
    }

    const output = await InstallerUtils.getCommandOutputOrNullIfMissing(
        [outputPath, '--version']);
    // Output is a string like "geckodriver 0.30.0 (sha1 date)\n"
    return output ? output.trim().split(' ')[1] : null;
  }

  /**
   * @param {string} browserVersion
   * @return {!Promise<string>}
   */
  async getBestDriverVersion(browserVersion) {
    // NOTE: geckodriver is currently independent of Firefox versions.
    const tag =
        await InstallerUtils.fetchLatestGitHubTag('mozilla/geckodriver');
    // NOTE: tags start with "v", but the version number reported by the binary
    // does not.  So that they can be directly compared, strip the "v" from the
    // tag.
    console.assert(tag[0] == 'v');
    return tag.substr(1);
  }

  /**
   * @param {string} driverVersion
   * @param {string} outputDirectory
   * @return {!Promise}
   */
  async install(driverVersion, outputDirectory) {
    let platform;
    let extension;
    let isZip;

    if (os.platform() == 'linux') {
      platform = 'linux64';
      extension = 'tar.gz';
      isZip = false;
    } else if (os.platform() == 'darwin') {
      if (process.arch == 'arm64') {
        platform = 'macos-aarch64';
      } else {
        platform = 'macos';
      }
      extension = 'tar.gz';
      isZip = false;
    } else if (os.platform() == 'win32') {
      platform = 'win64';
      extension = 'zip';
      isZip = true;
    } else {
      throw new Error(`Unrecognized platform: ${os.platform()}`);
    }

    const archiveUrl =
        'https://github.com/mozilla/geckodriver/releases/download' +
        `/v${driverVersion}` +
        `/geckodriver-v${driverVersion}-${platform}.${extension}`;

    let binaryName = 'geckodriver';
    if (os.platform() == 'win32') {
      binaryName += '.exe';
    }

    let outputName = this.getDriverName();
    if (os.platform() == 'win32') {
      outputName += '.exe';
    }

    const snapName = await this.getSnapName();
    if (snapName) {
      outputName = WRAPPED_DRIVER_NAME;
    }

    await InstallerUtils.installBinary(
        archiveUrl, binaryName, outputName,
        outputDirectory, isZip);

    const driverPath = path.join(outputDirectory, this.getDriverName());
    const wrappedPath = path.join(outputDirectory, WRAPPED_DRIVER_NAME);
    if (snapName) {
      // Remove any existing file first, in case it's a running executable.
      // See the similar note in InstallerUtils.extractFromNetworkArchive.
      if (await InstallerUtils.fileExists(driverPath)) {
        await fsPromises.unlink(driverPath);
      }
      await fsPromises.writeFile(driverPath, getSnapWrapperScript(snapName));
      await fsPromises.chmod(driverPath, 0o755);
    } else if (os.platform() == 'linux' &&
               await InstallerUtils.fileExists(wrappedPath)) {
      // Firefox is no longer a snap.  Clean up the binary that a previous
      // wrapper used.
      await fsPromises.unlink(wrappedPath);
    }
  }
}

module.exports = {FirefoxWebDriverInstaller};
